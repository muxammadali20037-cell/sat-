/**
 * Generates src/types/database.ts (Supabase `Database` type format) by introspecting a Postgres
 * database that has the migrations applied. Equivalent in shape to `supabase gen types typescript`,
 * but works against any Postgres URL without Docker.
 *
 *   DATABASE_URL=postgres://postgres@127.0.0.1:54329/satmaster_test npx tsx scripts/gen-types.ts
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { Client } from 'pg'

const url = process.env.DATABASE_URL ?? 'postgres://postgres@127.0.0.1:54329/satmaster_test'
const out = resolve(process.cwd(), 'src/types/database.ts')

const scalar: Record<string, string> = {
  uuid: 'string', text: 'string', varchar: 'string', bpchar: 'string', citext: 'string',
  date: 'string', timestamptz: 'string', timestamp: 'string', time: 'string', interval: 'string', inet: 'string',
  int2: 'number', int4: 'number', int8: 'number', float4: 'number', float8: 'number', numeric: 'number',
  bool: 'boolean', json: 'Json', jsonb: 'Json', void: 'undefined', record: 'Json',
}
const tsType = (udt: string): string => {
  if (udt.startsWith('_')) return `${tsType(udt.slice(1))}[]`
  return scalar[udt] ?? 'unknown'
}

async function main() {
  const db = new Client({ connectionString: url })
  await db.connect()

  const cols = (
    await db.query(`
      select c.table_name, c.column_name, c.udt_name, c.is_nullable = 'YES' as nullable,
             c.column_default is not null as has_default, c.is_identity = 'YES' as is_identity,
             c.is_generated = 'ALWAYS' or c.identity_generation = 'ALWAYS' as generated_always
        from information_schema.columns c
        join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
       where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
       order by c.table_name, c.ordinal_position`)
  ).rows as Array<{ table_name: string; column_name: string; udt_name: string; nullable: boolean; has_default: boolean; is_identity: boolean; generated_always: boolean }>

  const fks = (
    await db.query(`
      select con.conname, src.relname as table_name, tgt.relname as ref_table,
             array(select a.attname from unnest(con.conkey) with ordinality k(n, i)
                   join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.n order by k.i)::text[] as columns,
             array(select a.attname from unnest(con.confkey) with ordinality k(n, i)
                   join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k.n order by k.i)::text[] as ref_columns,
             exists (
               select 1 from pg_index ix
                where ix.indrelid = con.conrelid and ix.indisunique and ix.indpred is null
                  and (select array_agg(x order by x) from unnest(ix.indkey::int2[]) x)
                      = (select array_agg(x order by x) from unnest(con.conkey) x)
             ) as one_to_one
        from pg_constraint con
        join pg_class src on src.oid = con.conrelid
        join pg_class tgt on tgt.oid = con.confrelid
        join pg_namespace ns on ns.oid = src.relnamespace
       where con.contype = 'f' and ns.nspname = 'public'
       order by src.relname, con.conname`)
  ).rows as Array<{ conname: string; table_name: string; ref_table: string; columns: string[]; ref_columns: string[]; one_to_one: boolean }>

  const fns = (
    await db.query(`
      select p.proname, p.proretset as returns_set, p.pronargdefaults as n_defaults,
             coalesce(p.proargnames, '{}') as arg_names,
             coalesce(p.proargmodes::text[], '{}') as arg_modes,
             array(select t.typname from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality a(oid, i)
                   join pg_type t on t.oid = a.oid order by a.i)::text[] as arg_types,
             rt.typname::text as return_type
        from pg_proc p
        join pg_namespace n on n.oid = p.pronamespace
        join pg_type rt on rt.oid = p.prorettype
       where n.nspname = 'public' and rt.typname <> 'trigger' and p.prokind = 'f'
       order by p.proname`)
  ).rows as Array<{ proname: string; returns_set: boolean; n_defaults: number; arg_names: string[]; arg_modes: string[]; arg_types: string[]; return_type: string }>

  await db.end()

  const tables = new Map<string, typeof cols>()
  for (const c of cols) {
    if (!tables.has(c.table_name)) tables.set(c.table_name, [])
    tables.get(c.table_name)!.push(c)
  }

  const lines: string[] = []
  lines.push('// AUTO-GENERATED by scripts/gen-types.ts from supabase/migrations. Do not edit by hand.')
  lines.push('// Regenerate: npm run db:types')
  lines.push('')
  lines.push('export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]')
  lines.push('')
  lines.push('export type Database = {')
  lines.push('  __InternalSupabase: { PostgrestVersion: "12" }')
  lines.push('  public: {')
  lines.push('    Tables: {')
  for (const [table, columns] of tables) {
    lines.push(`      ${table}: {`)
    lines.push('        Row: {')
    for (const c of columns) lines.push(`          ${c.column_name}: ${tsType(c.udt_name)}${c.nullable ? ' | null' : ''}`)
    lines.push('        }')
    for (const kind of ['Insert', 'Update'] as const) {
      lines.push(`        ${kind}: {`)
      for (const c of columns) {
        if (c.generated_always) {
          lines.push(`          ${c.column_name}?: never`)
          continue
        }
        const optional = kind === 'Update' || c.nullable || c.has_default || c.is_identity
        lines.push(`          ${c.column_name}${optional ? '?' : ''}: ${tsType(c.udt_name)}${c.nullable ? ' | null' : ''}`)
      }
      lines.push('        }')
    }
    const rels = fks.filter((f) => f.table_name === table)
    if (rels.length === 0) {
      lines.push('        Relationships: []')
    } else {
      lines.push('        Relationships: [')
      for (const r of rels) {
        lines.push('          {')
        lines.push(`            foreignKeyName: "${r.conname}"`)
        lines.push(`            columns: [${r.columns.map((x) => `"${x}"`).join(', ')}]`)
        lines.push(`            isOneToOne: ${r.one_to_one}`)
        lines.push(`            referencedRelation: "${r.ref_table}"`)
        lines.push(`            referencedColumns: [${r.ref_columns.map((x) => `"${x}"`).join(', ')}]`)
        lines.push('          },')
      }
      lines.push('        ]')
    }
    lines.push('      }')
  }
  lines.push('    }')
  lines.push('    Views: { [_ in never]: never }')
  lines.push('    Functions: {')
  for (const f of fns) {
    const modes = f.arg_modes.length ? f.arg_modes : f.arg_types.map(() => 'i')
    const inArgs: Array<{ name: string; type: string }> = []
    const outCols: Array<{ name: string; type: string }> = []
    f.arg_types.forEach((t, i) => {
      const name = f.arg_names[i] ?? `arg${i}`
      if (modes[i] === 'i' || modes[i] === 'v' || modes[i] === 'b') inArgs.push({ name, type: tsType(t) })
      if (modes[i] === 't' || modes[i] === 'o' || modes[i] === 'b') outCols.push({ name, type: tsType(t) })
    })
    const firstDefault = inArgs.length - f.n_defaults
    const args = inArgs.length
      ? `{ ${inArgs.map((a, i) => `${a.name}${i >= firstDefault ? '?' : ''}: ${a.type}`).join('; ')} }`
      : 'Record<PropertyKey, never>'
    let ret: string
    if (outCols.length) {
      const obj = `{ ${outCols.map((c) => `${c.name}: ${c.type}`).join('; ')} }`
      ret = f.returns_set ? `${obj}[]` : obj
    } else {
      ret = tsType(f.return_type) + (f.returns_set ? '[]' : '')
    }
    lines.push(`      ${f.proname}: { Args: ${args}; Returns: ${ret} }`)
  }
  lines.push('    }')
  lines.push('    Enums: { [_ in never]: never }')
  lines.push('    CompositeTypes: { [_ in never]: never }')
  lines.push('  }')
  lines.push('}')
  lines.push('')
  lines.push("type PublicSchema = Database['public']")
  lines.push("export type Tables<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Row']")
  lines.push("export type TablesInsert<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Insert']")
  lines.push("export type TablesUpdate<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Update']")
  lines.push("export type DbFunctions = PublicSchema['Functions']")
  lines.push('')

  mkdirSync(resolve(out, '..'), { recursive: true })
  writeFileSync(out, lines.join('\n'))
  console.log(`wrote ${out} (${tables.size} tables, ${fns.length} functions, ${fks.length} relationships)`)
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
