/**
 * Course pack pipeline: validates content/courses/*.json and writes the bundled module the admin
 * "Import bundled courses" button reads.
 *
 *   npx tsx scripts/courses/build.ts --check   # validate only
 *   npx tsx scripts/courses/build.ts           # validate, order lessons by SAT skill order, write the bundle
 *
 * Checks: schema, known skill codes of the course's subject, unique course and lesson slugs, one lesson
 * per skill per course, every section heading present, KaTeX renders.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import katex from 'katex'
import { courseFileSchema, type CourseFile } from '../../src/features/courses/bundle-schema'
import { collectMath, parseRichText } from '../../src/lib/rich-text/tokenize'

const ROOT = resolve(__dirname, '../..')
const DIR = resolve(ROOT, 'content/courses')
const REFERENCE = resolve(ROOT, 'supabase/migrations/20261102001000_reference_data.sql')
const BUNDLE = resolve(ROOT, 'src/features/courses/bundled.generated.ts')
const checkOnly = process.argv.includes('--check')

// Skill code → [subject, order] in the official domain/skill order of the reference data.
const sql = readFileSync(REFERENCE, 'utf8')
// Domain rows: (subject, code, name, description, weight, position).
const domainSubject = new Map([...sql.matchAll(/\('(math|reading_writing)','([a-z_]+)','[^']+','[^']*',(\d+),(\d+)\)/g)].map((m) => [m[2]!, { subject: m[1]!, pos: Number(m[4]) }]))
const skillInfo = new Map(
  [...sql.matchAll(/\('([a-z_]+)','([a-z0-9_]+)','[^']+','[^']*',(\d+)\)/g)].map((m) => {
    const d = domainSubject.get(m[1]!)
    return [m[2]!, { subject: d?.subject ?? '', order: (d?.pos ?? 0) * 100 + Number(m[3]) }]
  }),
)
const SECTIONS = ['**Key idea**', '**Worked example', '**Common traps**', '**Quick self-check**']

let failed = false
const courses: CourseFile[] = []
const courseSlugs = new Set<string>()
for (const file of readdirSync(DIR).filter((f) => f.endsWith('.json')).sort()) {
  const errors: string[] = []
  const parsed = courseFileSchema.safeParse(JSON.parse(readFileSync(resolve(DIR, file), 'utf8')))
  if (!parsed.success) {
    console.error(`✗ ${file}\n  ${parsed.error.issues.map((i) => `${i.path.join('.')}: ${i.message}`).join('\n  ')}`)
    failed = true
    continue
  }
  const c = parsed.data
  if (courseSlugs.has(c.slug)) errors.push(`duplicate course slug ${c.slug}`)
  courseSlugs.add(c.slug)
  const lessonSlugs = new Set<string>()
  const skills = new Set<string>()
  for (const l of c.lessons) {
    const info = skillInfo.get(l.skill)
    if (!info) errors.push(`${l.slug}: unknown skill ${l.skill}`)
    else if (info.subject !== c.subject) errors.push(`${l.slug}: skill ${l.skill} is not a ${c.subject} skill`)
    if (lessonSlugs.has(l.slug)) errors.push(`duplicate lesson slug ${l.slug}`)
    if (skills.has(l.skill)) errors.push(`${l.slug}: a second lesson for ${l.skill}`)
    lessonSlugs.add(l.slug)
    skills.add(l.skill)
    for (const s of SECTIONS) if (!l.body.includes(s)) errors.push(`${l.slug}: missing section ${s}`)
    for (const tex of collectMath(parseRichText(l.body))) {
      try {
        katex.renderToString(tex, { throwOnError: true, strict: 'ignore' })
      } catch (e) {
        errors.push(`${l.slug}: KaTeX cannot render "${tex.slice(0, 40)}": ${(e as Error).message.split('\n')[0]}`)
      }
    }
  }
  c.lessons.sort((a, b) => (skillInfo.get(a.skill)?.order ?? 0) - (skillInfo.get(b.skill)?.order ?? 0))
  if (errors.length) {
    failed = true
    console.error(`✗ ${file}\n  ${errors.join('\n  ')}`)
  } else console.log(`✓ ${file} (${c.lessons.length} lessons)`)
  courses.push(c)
}
if (failed) process.exit(1)
if (!checkOnly) {
  writeFileSync(
    BUNDLE,
    [
      '// GENERATED by scripts/courses/build.ts — do not edit by hand.',
      `export const BUNDLED_COURSES_JSON = ${JSON.stringify(JSON.stringify(courses))}`,
      '',
    ].join('\n'),
  )
  console.log(`wrote ${BUNDLE.replace(ROOT + '/', '')}`)
}
